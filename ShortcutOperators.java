package ShortcutOperators;

public class ShortcutOperators {

	public static void main( String [] args)
	{
		int a = 6;
		int b = 2;
		
		System.out.println( "At thr beginning, a is " + a );
		
		System.out.println( " \nIncrement a with prefix notation: " + ++a);
		
		System.out.println( "\nIn the end, a is " + a );
		
		//B
		
		System.out.println( "\nAt the beginning, b is " + b );
		
		System.out.println( "\nIncrement b with postfix notation: " +b++);
		
		System.out.println( "\nIn the end, b is " + b );
			
	}
}
