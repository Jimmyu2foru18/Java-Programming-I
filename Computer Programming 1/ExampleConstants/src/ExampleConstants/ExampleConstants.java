package ExampleConstants;


public class ExampleConstants {

	public static void main (String [] args )
	{
		final char ZORRO = 'Z';
		final double PI = 3.14159;
		final int DAYS_IN_LEAP_YEAR = 366,
				DAYS_IN_NON_LEAP_YEAR = 365;
		
		System.out.println("The value of constant ZORRO is " + ZORRO );
		
		System.out.println("\nThe value of constant PI is " + PI );
		
		System.out.println("\nThe number of days in a leap year is " + DAYS_IN_LEAP_YEAR );
		
		System.out.println("\nThe number of days in a non-leap year is " + DAYS_IN_NON_LEAP_YEAR );
		
	}
}
